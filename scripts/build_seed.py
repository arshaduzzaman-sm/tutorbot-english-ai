#!/usr/bin/env python3
"""Build supabase/seed.sql from the versioned files in content/.

Usage: python3 scripts/build_seed.py [--check]

--check only validates the content and fails if seed.sql is out of date.
Content stays in Git (reviewable); the database is filled from it.
UUIDs are derived from stable content ids (uuid5) so re-imports are stable.
"""
from __future__ import annotations

import json
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = ROOT / "supabase" / "seed.sql"
NS = uuid.UUID("6f1c2b8e-3d4a-4f5b-9c1d-2e3f4a5b6c7d")

DIFFICULTIES = {"beginner", "intermediate", "advanced"}
SECTION_KINDS = {"learn", "see", "try", "check", "review"}

# Clearly fake demo accounts for local development only (SPEC Part B step 7).
DEMO_USERS = [
    {"email": "demo.student@example.test", "password": "DemoStudent-123!", "name": "Demo Student", "roles": []},
    {"email": "demo.admin@example.test", "password": "DemoAdmin-123!", "name": "Demo Admin", "roles": ["admin"]},
]


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value: object) -> str:
    """Quote a value as a SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return q(json.dumps(value, ensure_ascii=False)) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def text_array(values: list[str]) -> str:
    if not values:
        return "'{}'::text[]"
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]"


class ContentError(Exception):
    pass


def load_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def build() -> str:
    errors: list[str] = []
    out: list[str] = [
        "-- GENERATED by scripts/build_seed.py from content/. Do not edit by hand.",
        "-- Local development data only. Demo passwords are fake and public.",
        "",
    ]

    levels = load_json(CONTENT / "levels.json")
    level_ids = {}
    out.append("-- Learning levels")
    for lv in levels:
        level_ids[lv["code"]] = uid("level", str(lv["code"]))
        out.append(
            "insert into public.learning_levels (id, code, slug, name, cefr, description) values ("
            f"{q(level_ids[lv['code']])}, {lv['code']}, {q(lv['slug'])}, {q(lv['name'])}, {q(lv['cefr'])}, {q(lv['description'])});"
        )

    cats_file = load_json(CONTENT / "question_categories.json")
    source = cats_file["_source"]
    cat_ids = {}
    out += ["", "-- Question categories (22 PTE Academic task types)"]
    for i, c in enumerate(cats_file["categories"], start=1):
        cat_ids[c["code"]] = uid("category", c["code"])
        skills = "array[" + ", ".join(q(s) for s in c["skills"]) + "]::public.skill[]"
        out.append(
            "insert into public.question_categories (id, code, name, section, skills, sort_order, description, official_source_url, verified) values ("
            f"{q(cat_ids[c['code']])}, {q(c['code'])}, {q(c['name'])}, {q(c['section'])}, {skills}, {i}, "
            f"{q(c.get('description', ''))}, {q(source)}, true);"
        )
    if len(cat_ids) != 22:
        errors.append(f"expected 22 question categories, found {len(cat_ids)}")

    out += ["", "-- Lessons"]
    lesson_count = 0
    for path in sorted((CONTENT / "lessons").glob("*.json")):
        data = load_json(path)
        level_id = level_ids.get(data["level_code"])
        if not level_id:
            errors.append(f"{path.name}: unknown level_code {data['level_code']}")
            continue
        for order, lesson in enumerate(data["lessons"], start=1):
            lesson_count += 1
            lid = uid("lesson", lesson["slug"])
            out.append(
                "insert into public.lessons (id, slug, learning_level_id, title, summary, sort_order, estimated_minutes, status) values ("
                f"{q(lid)}, {q(lesson['slug'])}, {q(level_id)}, {q(lesson['title'])}, {q(lesson['summary'])}, {order}, "
                f"{lesson.get('estimated_minutes', 10)}, 'published');"
            )
            for s_order, sec in enumerate(lesson["sections"], start=1):
                if sec["kind"] not in SECTION_KINDS:
                    errors.append(f"{lesson['slug']}: bad section kind {sec['kind']}")
                for ex in sec.get("exercises", []):
                    if ex.get("type") == "single_choice" and ex["answer"] not in ex["options"]:
                        errors.append(f"{lesson['slug']}/{ex['id']}: answer not in options")
                out.append(
                    "insert into public.lesson_sections (id, lesson_id, kind, sort_order, title, body_md, exercises) values ("
                    f"{q(uid('section', lesson['slug'] + ':' + str(s_order)))}, {q(lid)}, {q(sec['kind'])}, {s_order}, "
                    f"{q(sec.get('title', ''))}, {q(sec.get('body_md', ''))}, {q(sec.get('exercises', []))});"
                )

    out += ["", "-- Sample questions"]
    seen: set[str] = set()
    per_cat: dict[str, int] = {}
    for path in sorted((CONTENT / "questions").glob("*.json")):
        for item in load_json(path)["questions"]:
            ext = item["external_id"]
            if ext in seen:
                errors.append(f"duplicate external_id {ext}")
            seen.add(ext)
            if item["category"] not in cat_ids:
                errors.append(f"{ext}: unknown category {item['category']}")
                continue
            if item["difficulty"] not in DIFFICULTIES:
                errors.append(f"{ext}: bad difficulty")
            for field in ("instructions", "explanation", "learning_objective"):
                if not item.get(field):
                    errors.append(f"{ext}: missing {field}")
            options = item.get("options", [])
            if options and not any(o["is_correct"] for o in options):
                errors.append(f"{ext}: no correct option")
            if options:
                correct = sorted(o["label"] for o in options if o["is_correct"])
                if correct != sorted(item["answer"].get("correct", [])):
                    errors.append(f"{ext}: answer.correct does not match options")
            per_cat[item["category"]] = per_cat.get(item["category"], 0) + 1
            qid = uid("question", ext)
            out.append(
                "insert into public.questions (id, external_id, category_id, difficulty, instructions, content, answer, explanation, "
                "learning_objective, scoring_criteria, key_points, status) values ("
                f"{q(qid)}, {q(ext)}, {q(cat_ids[item['category']])}, {q(item['difficulty'])}, {q(item['instructions'])}, "
                f"{q(item['content'])}, {q(item['answer'])}, {q(item['explanation'])}, {q(item['learning_objective'])}, "
                f"{text_array(item.get('scoring_criteria', []))}, {text_array(item.get('key_points', []))}, 'published');"
            )
            for o_order, opt in enumerate(options, start=1):
                out.append(
                    "insert into public.question_options (id, question_id, label, body, is_correct, sort_order) values ("
                    f"{q(uid('option', ext + ':' + opt['label']))}, {q(qid)}, {q(opt['label'])}, {q(opt['body'])}, {q(opt['is_correct'])}, {o_order});"
                )
    for code in cat_ids:
        if per_cat.get(code, 0) < 2:
            errors.append(f"category {code} has fewer than 2 questions")

    out += ["", "-- Demo users (fake, local only). The signup trigger creates profiles and student roles."]
    for user in DEMO_USERS:
        user_id = uid("demo-user", user["email"])
        meta = {"display_name": user["name"], "age_confirmed": "true", "terms_accepted": "true"}
        out.append(
            "insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, "
            "raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, "
            "email_change_token_new, email_change) values ("
            f"'00000000-0000-0000-0000-000000000000', {q(user_id)}, 'authenticated', 'authenticated', {q(user['email'])}, "
            f"extensions.crypt({q(user['password'])}, extensions.gen_salt('bf')), now(), "
            f"'{{\"provider\":\"email\",\"providers\":[\"email\"]}}'::jsonb, {q(meta)}, now(), now(), '', '', '', '');"
        )
        out.append(
            "insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at) values ("
            f"{q(uid('demo-identity', user['email']))}, {q(user_id)}, {q(user_id)}, "
            f"{q({'sub': user_id, 'email': user['email'], 'email_verified': True})}, 'email', now(), now(), now());"
        )
        for role in user["roles"]:
            out.append(f"insert into public.user_roles (user_id, role) values ({q(user_id)}, {q(role)});")
    if errors:
        raise ContentError("\n".join(errors))
    return "\n".join(out) + "\n"


def main() -> int:
    try:
        sql = build()
    except ContentError as exc:
        print(f"Content errors:\n{exc}", file=sys.stderr)
        return 1
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != sql:
            print("supabase/seed.sql is out of date. Run: python3 scripts/build_seed.py", file=sys.stderr)
            return 1
        print("Content valid; seed.sql up to date.")
        return 0
    OUT.write_text(sql, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
